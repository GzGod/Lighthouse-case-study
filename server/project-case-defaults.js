function number(value) {
  return Number(value || 0).toLocaleString('en-US');
}

function usd(value, digits = 2) {
  return `$${Number(value || 0).toLocaleString('en-US', { minimumFractionDigits: digits, maximumFractionDigits: digits })}`;
}

async function seedProjectCasePages(pool) {
  for (const [slug, pageData] of Object.entries(PROJECT_CASE_PAGES)) {
    await pool.query(
      `INSERT INTO project_case_pages (project_id, page_data, updated_at)
       SELECT id, $2::jsonb, NOW()
       FROM projects
       WHERE slug = $1
       ON CONFLICT (project_id) DO UPDATE
       SET page_data = EXCLUDED.page_data || project_case_pages.page_data,
           updated_at = NOW()`,
      [slug, JSON.stringify(pageData)]
    );
  }
}

